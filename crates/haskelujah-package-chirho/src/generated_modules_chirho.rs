//! Modules Cabal generates for a package instead of shipping them (row 703).
//!
//! `Paths_<pkg>` is generated here in the shape Cabal's user guide ("Accessing data files from
//! package code") and its `templates/Paths_pkg.template.hs` give it:
//! - the module name, the package name with every `-` replaced by `_`;
//! - its exports, `version`, the six directory getters and `getDataFileName`;
//! - an exact `version`;
//! - the run-time override variables `<pkg>_<dir>`, where `<dir>` is `bindir`, `libdir`,
//!   `dynlibdir`, `datadir`, `libexecdir` or `sysconfdir`. That is the source spelling; the
//!   guide's "libexedir" appears only in a comment.
//!
//! The getters are a source-check limitation, not Cabal's behavior. Cabal falls back to the
//! configured installation directories, and a source package has none, so a getter returns its
//! override when one is set and otherwise fails with an explicit `IOError`. An unused listed
//! `Paths_` module therefore proves only that this shape compiles, not that Cabal's run-time paths
//! work. `PackageInfo_<pkg>` has no generator here, so install refuses packages that list it.

use crate::version_chirho::VersionChirho;

const MODULE_TOKEN_CHIRHO: &str = "@MODULE@";
const PACKAGE_ID_TOKEN_CHIRHO: &str = "@PKGID@";
const ENV_PREFIX_TOKEN_CHIRHO: &str = "@PKGVAR@";
const DIGITS_TOKEN_CHIRHO: &str = "@DIGITS@";

/// The generated `Paths_` module, with POSIX path separators as Cabal emits off Windows.
const PATHS_MODULE_TEMPLATE_CHIRHO: &str = r#"{-# LANGUAGE NoRebindableSyntax #-}
-- Generated by haskelujah install in the shape of Cabal's Paths_ module for @PKGID@.
-- Install writes this file; edits are lost when the package is installed again.
-- A Haskelujah source package installs no binaries, libraries, data or configuration,
-- so each directory comes only from Cabal's documented environment override
-- @PKGVAR@_<dir>. Unlike Cabal's module, an unset override is an explicit IOError,
-- because no configured installation directory exists to fall back to.
module @MODULE@ (
    version,
    getBinDir, getLibDir, getDynLibDir, getDataDir, getLibexecDir,
    getDataFileName, getSysconfDir
  ) where

import Data.Version (Version(..))
import System.Environment (lookupEnv)
import Prelude

-- | The package version.
version :: Version
version = Version @DIGITS@ []

-- | The name a data file would have under 'getDataDir'. No check is made that the file is
-- listed in the package's data-files field.
getDataFileName :: FilePath -> IO FilePath
getDataFileName nameChirho = do
  dirChirho <- getDataDir
  return (dirChirho `joinFileNameChirho` nameChirho)

getBinDir, getLibDir, getDynLibDir, getDataDir, getLibexecDir, getSysconfDir :: IO FilePath
getBinDir = overrideDirChirho "bindir"
getLibDir = overrideDirChirho "libdir"
getDynLibDir = overrideDirChirho "dynlibdir"
getDataDir = overrideDirChirho "datadir"
getLibexecDir = overrideDirChirho "libexecdir"
getSysconfDir = overrideDirChirho "sysconfdir"

overrideDirChirho :: String -> IO FilePath
overrideDirChirho varChirho = do
  overrideChirho <- lookupEnv ("@PKGVAR@_" ++ varChirho)
  case overrideChirho of
    Just dirChirho -> return dirChirho
    Nothing ->
      ioError (userError ("@PKGID@ is a Haskelujah source package with no installed "
        ++ varChirho ++ "; set @PKGVAR@_" ++ varChirho))

joinFileNameChirho :: String -> String -> FilePath
joinFileNameChirho "" fnameChirho = fnameChirho
joinFileNameChirho "." fnameChirho = fnameChirho
joinFileNameChirho dirChirho "" = dirChirho
joinFileNameChirho dirChirho@(cChirho:csChirho) fnameChirho
  | isPathSeparatorChirho (lastCharChirho cChirho csChirho) = dirChirho ++ fnameChirho
  | otherwise = dirChirho ++ pathSeparatorChirho : fnameChirho
  where
    lastCharChirho xChirho [] = xChirho
    lastCharChirho _ (xChirho:xsChirho) = lastCharChirho xChirho xsChirho

pathSeparatorChirho :: Char
pathSeparatorChirho = '/'

isPathSeparatorChirho :: Char -> Bool
isPathSeparatorChirho cChirho = cChirho == '/'
"#;

/// The part of a generated module's name, and of its environment variables, that names the
/// package: the package name with every `-` replaced by `_`, as Cabal's `manglePkgName` does.
pub fn mangled_package_name_chirho(package_name_chirho: &str) -> String {
    package_name_chirho.replace('-', "_")
}

/// The name of the `Paths_` module Cabal generates for a package.
pub fn paths_module_name_chirho(package_name_chirho: &str) -> String {
    format!("Paths_{}", mangled_package_name_chirho(package_name_chirho))
}

/// The name of the `PackageInfo_` module Cabal generates for a package.
pub fn package_info_module_name_chirho(package_name_chirho: &str) -> String {
    format!(
        "PackageInfo_{}",
        mangled_package_name_chirho(package_name_chirho)
    )
}

/// Whether a package name keeps the generated Haskell well formed: non-empty ASCII letters,
/// digits and inner hyphens, which also covers every name Cabal accepts.
pub fn is_safe_package_name_chirho(package_name_chirho: &str) -> bool {
    !package_name_chirho.is_empty()
        && !package_name_chirho.starts_with('-')
        && !package_name_chirho.ends_with('-')
        && package_name_chirho
            .chars()
            .all(|char_chirho| char_chirho.is_ascii_alphanumeric() || char_chirho == '-')
}

/// Render the `Paths_` module for `package_name_chirho` at `version_chirho`.
pub fn render_paths_module_chirho(
    package_name_chirho: &str,
    version_chirho: &VersionChirho,
) -> Result<String, String> {
    if !is_safe_package_name_chirho(package_name_chirho) {
        return Err(format!(
            "package name `{package_name_chirho}` is not a valid Cabal package name"
        ));
    }
    if version_chirho.components_chirho.is_empty() {
        return Err(format!(
            "package `{package_name_chirho}` has an empty version"
        ));
    }
    let digits_chirho = format!(
        "[{}]",
        version_chirho
            .components_chirho
            .iter()
            .map(u32::to_string)
            .collect::<Vec<_>>()
            .join(",")
    );
    Ok(PATHS_MODULE_TEMPLATE_CHIRHO
        .replace(
            MODULE_TOKEN_CHIRHO,
            &paths_module_name_chirho(package_name_chirho),
        )
        .replace(
            PACKAGE_ID_TOKEN_CHIRHO,
            &format!("{package_name_chirho}-{version_chirho}"),
        )
        .replace(
            ENV_PREFIX_TOKEN_CHIRHO,
            &mangled_package_name_chirho(package_name_chirho),
        )
        .replace(DIGITS_TOKEN_CHIRHO, &digits_chirho))
}
